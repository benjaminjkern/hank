// Copy Prisma's generated enums into src/shared/generated/ so client and shared
// code get the database enums without importing anything from src/server/.
//
// Runs as the second half of `pnpm db:generate` (which postinstall and build
// both go through), so the copy is rewritten every time the Prisma client is —
// it can't drift from the schema. Prisma's enums.ts is self-contained (no
// imports), which is what makes a verbatim copy safe.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const from = path.join(root, "src/server/generated/prisma/enums.ts");
const to = path.join(root, "src/shared/generated/enums.ts");

const source = fs.readFileSync(from, "utf8");
if (/^\s*import\s/m.test(source)) {
  throw new Error(
    `${from} now has imports; a verbatim copy into src/shared would pull server code along. Update scripts/syncSharedEnums.mjs.`,
  );
}
fs.mkdirSync(path.dirname(to), { recursive: true });
fs.writeFileSync(
  to,
  `// GENERATED by scripts/syncSharedEnums.mjs from the Prisma schema — do not edit.\n${source}`,
);
console.log(`synced Prisma enums → ${path.relative(root, to)}`);
